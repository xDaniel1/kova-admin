// Live status card (Home): Android Auto column counts only Android installs that read Tower.
import { mkdtempSync, mkdirSync, copyFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url)), root = join(here, '..');
const tmp = mkdtempSync(join(tmpdir(), 'tower-live-'));
process.on('exit', () => rmSync(tmp, { recursive: true, force: true }));
mkdirSync(join(tmp, 'js'), { recursive: true });
writeFileSync(join(tmp, 'package.json'), '{"type":"module"}');
copyFileSync(join(root, 'js', 'util.js'), join(tmp, 'js', 'util.js'));
copyFileSync(join(root, 'js', 'live-status.js'), join(tmp, 'js', 'live-status.js'));
copyFileSync(join(here, 'stubs-live', 'api.js'), join(tmp, 'js', 'api.js'));
const api = await import(join(tmp, 'js', 'api.js'));
const { liveStatusCard } = await import(join(tmp, 'js', 'live-status.js'));
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const row = o => ({ platform: 'android', version: '1.0.0', build: '2', n: 40, beta: 0, last: '2026-11-22T00:00:00Z', car_keys: [], ...o });
api.ctl.config = [{ key: 'features', value: { android_auto: true } }];
api.ctl.builds = [row({ reports_keys: true, no_keys: 39 })];
let out = (await liveStatusCard()).s;
ok(out.includes('1 of 40 read Tower') && out.includes('android_auto'), 'mixed Android build-2 row: "1 of 40 read Tower"');
api.ctl.builds = [row({ reports_keys: true, no_keys: undefined })];
out = (await liveStatusCard()).s;
ok(out.includes('count needs migration 0023'), 'no per-install count: says it needs 0023');
api.ctl.builds = [row({ reports_keys: false, no_keys: 40 })];
out = (await liveStatusCard()).s;
ok(out.includes("doesn't read Tower") || out.includes('doesn&#39;t read Tower'), 'Android build 2 without keys: does not read Tower');
api.ctl.builds = [row({ build: '3', reports_keys: true, no_keys: 0, n: 5 })];
out = (await liveStatusCard()).s;
ok(out.includes('android_auto') && !out.includes('of 5 read Tower'), 'Android build 3: full row, no partial note');
